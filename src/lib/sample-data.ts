// --- Small helpers used by the preview pages -------------------------------

export function getTrip(tripId: string): Trip | undefined {
  return trips.find((trip) => trip.id === tripId);
}

export function getTripMember(trip: Trip, memberId: string): Member | undefined {
  return trip.members.find((member) => member.id === memberId);
}

export function getMemberName(trip: Trip, memberId: string): string {
  return getTripMember(trip, memberId)?.name ?? "Former member";
}

export function getItinerary(tripId: string): ItineraryItem[] {
  return itinerary.filter((item) => item.tripId === tripId);
}

export function getExpenses(tripId: string): Expense[] {
  return expenses.filter((expense) => expense.tripId === tripId);
}

export function getPolls(tripId: string): Poll[] {
  return polls.filter((poll) => poll.tripId === tripId);
}

export function getPackingItems(tripId: string): PackingItem[] {
  return packingItems.filter((item) => item.tripId === tripId);
}

export function getNotes(tripId: string): TripNote[] {
  return notes.filter((note) => note.tripId === tripId);
}

export function getInvitations(kind: Invitation["kind"]): Invitation[] {
  return invitations.filter((invitation) => invitation.kind === kind);
}

export function getCurrentUser(): Member {
  return { ...people.khushi, role: "member" };
}

export function getMemberById(memberId: string): Member | undefined {
  const person = (people as Record<string, Person>)[memberId];
  return person ? { ...person, role: "member" } : undefined;
}
